"""Write docs/results.md from results/<season>/ files (guide Section 10, item 4).

Every number in the report is read from results/; nothing is typed by hand.
H1 and H2 verdicts follow docs/preregistration.md Section 6.

Usage:  python scripts/write_results.py
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"


def _fmt(v, d=3):
    return "n/a" if v is None or pd.isna(v) else f"{v:.{d}f}"


def h1_verdict(b: dict) -> str:
    if b["upper95"] < 1:
        return "SUPPORTED"
    if b["relative_wis"] < 1:
        return "PARTLY SUPPORTED"
    return "NOT SUPPORTED"


def h2_verdict(cov50: float, cov90: float) -> str:
    ok90, ok50 = 0.82 <= cov90 <= 0.95, 0.42 <= cov50 <= 0.58
    return "SUPPORTED" if ok90 and ok50 else "PARTLY SUPPORTED" if ok90 or ok50 else "NOT SUPPORTED"


def season_section(season: int) -> list[str]:
    d = RESULTS / str(season)
    if not (d / "run_meta.json").exists():
        return [f"## {season}\n", "Not run.\n"]
    meta = json.loads((d / "run_meta.json").read_text(encoding="utf-8"))
    summ = pd.read_csv(d / "summary.csv")
    scores = pd.read_csv(d / "scores.csv")
    comp = meta["comparator"]
    out = [f"## {season}: {meta['label']}\n",
           f"- Command: `{meta['command']}`",
           f"- Code commit: `{meta['code_commit']}`",
           f"- Run: {meta['started_utc']} to {meta['finished_utc']} (UTC)",
           f"- Comparator: **{comp}**",
           f"- Origins: {len(meta['origins'])}; Model A fit origins: {len(meta['model_a_fit_origins'])}",
           f"- Forecasts made per model (unit x origin x horizon): {meta['forecasts_made']}",
           f"- Forecasts scored (common to all models): {meta['forecasts_scored_common']}",
           f"- Target weeks without truth (excluded): {len(meta['truth_missing_target_weeks'])} "
           f"({', '.join(meta['truth_missing_target_weeks']) or 'none'})",
           f"- Not produced: {len(meta['not_produced'])} model-origin combinations "
           + (f"({', '.join(sorted({n['model'] for n in meta['not_produced']}))})" if meta['not_produced'] else ""),
           ""]
    if meta["label"] == "VALIDATION":
        out.append("> These are VALIDATION results: Model A was tuned and the comparator chosen on this season, so they are optimistic.\n")
    # Hypotheses
    if "ensemble" in set(scores["model"]):
        out.append("### Hypotheses\n")
        out.append("| Hypothesis | Scale | Estimate | 95% interval | Verdict |\n| --- | --- | --- | --- | --- |")
        for scale in ("count", "log1p"):
            b = meta["bootstrap"].get(f"ensemble|{scale}|h1-3")
            if b:
                out.append(f"| H1 relative WIS, ensemble vs {comp}, h1-3 | {scale} | {_fmt(b['relative_wis'])} | "
                           f"[{_fmt(b['lower95'])}, {_fmt(b['upper95'])}] | {h1_verdict(b)}{' (primary)' if scale == 'count' else ''} |")
        e = scores[(scores["model"] == "ensemble") & (scores["scale"] == "count") & (scores["horizon"].isin([1, 2, 3]))]
        out.append(f"| H2 coverage, ensemble, h1-3 | count | 50%: {_fmt(e['cov50'].mean())}; 90%: {_fmt(e['cov90'].mean())} | "
                   f"bands [0.42, 0.58] and [0.82, 0.95] | {h2_verdict(e['cov50'].mean(), e['cov90'].mean())} |")
        b4 = meta["bootstrap"].get(f"ensemble|count|h4")
        if b4:
            out.append(f"| Secondary: relative WIS h4 | count | {_fmt(b4['relative_wis'])} | [{_fmt(b4['lower95'])}, {_fmt(b4['upper95'])}] | (secondary) |")
        out.append("")
        out.append("### All models vs comparator (bootstrap, horizons 1-3)\n")
        out.append("| Model | Scale | Relative WIS | 95% interval |\n| --- | --- | --- | --- |")
        for k, b in sorted(meta["bootstrap"].items()):
            m, scale, hz = k.split("|")
            if hz == "h1-3":
                out.append(f"| {m} | {scale} | {_fmt(b['relative_wis'])} | [{_fmt(b['lower95'])}, {_fmt(b['upper95'])}] |")
        out.append("")
    for by, title in (("all", "Overall"), ("horizon", "By horizon"), ("phase", "By epidemic phase (H4, descriptive)"), ("unit", "By unit")):
        t = summ[summ["breakdown"] == by]
        out.append(f"### {title}\n")
        for scale in ("count", "log1p"):
            ts = t[t["scale"] == scale][["level", "model", "n", "mean_wis", "relative_wis", "mae", "cov50", "cov90"]]
            out.append(f"Scale: **{scale}**\n")
            out.append(ts.to_markdown(index=False, floatfmt=".3f"))
            out.append("")
    return out


def main() -> None:
    lines = ["# DengueCast BD: results\n",
             "Generated by `python scripts/write_results.py` from `results/`. Every number below is read from those files.",
             "Plan: `docs/preregistration.md` (tag `prereg-v1`); deviations: `docs/DEVIATIONS.md`.\n"]
    lines += season_section(2024)
    lines += season_section(2023)
    (ROOT / "docs" / "results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Wrote docs/results.md")


if __name__ == "__main__":
    main()
